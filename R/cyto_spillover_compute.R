## CYTO_SPILLOVER_COMPUTE ------------------------------------------------------

#' Compute Spillover Matrix
#'
#' \code{cyto_spillover_compute} automatically computes the fluorescent
#' spillover matrix for a set of single colour compensation controls using
#' either the method proposed by Bagwell et al. (1993) or the more recent method
#' proposed by Roca et al. (2021).
#'
#' The method proposed by Roca et al. (2021) is now the default method, and has
#' been implemented in \code{cyto_spillover_compute} as a fully automated
#' algorithm to compute the spillover matrix. Users simply need to ensure that
#' the channel associated with each control is annotated in the
#' \code{cyto_details()} of the supplied data.
#'
#' The method proposed by Bagwell et al. (1993) is also supported but is
#' implemented as a semi-automated approach as it requires gating of the
#' positive and negative signal within each single colour control to accurately
#' compute the spillover coefficients. Gating is performed on a per channel
#' basis with the user manually drawing interval gates around the positive and
#' negative signal for each control. If a universal unstained control is
#' supplied, users are only asked to gate the positive signal for each control
#' and the unstained control will be used as the reference for the negative
#' signal in each channel.
#'
#' The computed spillover is returned as a matrix and exported as a csv file
#' specified by the \code{save_as} argument. To assess the quality of the
#' compensation, refer to \code{\link{cyto_spillover_edit}} and
#' \code{\link{cyto_plot_compensation}}. Users can apply their computed
#' spillover matrices to their samples using \code{\link{cyto_compensate}}.
#'
#' @param x object of class \code{\link[flowCore:flowSet-class]{flowSet}} or
#'   \code{\link[flowWorkspace:GatingSet-class]{GatingSet}} containing
#'   transformed and gated compensation controls.
#' @param parent name of the population to use for the spillover calculation
#'   when a GatingSet object is supplied, set to the last node of the GatingSet
#'   by default (e.g. "Single Cells"). For greater flexibility, users can
#'   specify a parent population for each control, which will be extracted for
#'   the spillover calculation (e.g. Lymphocytes for CD4 APC or Myeloid Cells
#'   for CD11b FITC). The parent populations for each control can also be
#'   specified in a \code{parent} column in the channel match CSV file or in
#'   \code{cyto_details}.
#' @param select passed to \code{\link{cyto_select}} to select the samples
#'   required to compute the spillover matrix.
#' @param channels names of the channels or markers for which spillover
#'   coefficients should be computed, set to all area fluorescent channels by
#'   default.
#' @param gate indicates whether to \code{draw} or use \code{auto} gating
#'   methods to gate the negative and positive populations for each control.
#'   Gating is optional for \code{"Autospill"} and \code{"CytoDecode"} methods
#'   but is recommended to achieve better results and ensure compatibility with
#'   \code{cyto_panel_design()}. Set to \code{"draw"} by default to allow for
#'   more flexibility over gating. For \code{gate = "draw"} users can also
#'   specify whether to gate the 1D histograms or 2D scatter plots 1D or 2D
#'   suffix to \code{gate}. For example, to gate in 2D set \code{gate =
#'   "draw-2D"} which is the new default manual gating method.
#' @param type options include \code{"Bagwell" or "autocomp"}, \code{"Roca" or
#'   "autospill"} or \code{"CytoDecode"} to indicate which method to use when
#'   computing the spillover matrix, set to \code{"CytoDecode"} by default.
#' @param save_as name of a csv file to which the computed spillover matrix
#'   should be written, set to \code{Spillover-Matrix.csv} prefixed with the
#'   date by default.
#' @param gatingTemplate name of \code{gatingTemplate} csv file to which the
#'   \code{gatingTemplate} entries for the \code{GatingSet} method should be
#'   saved, set to \code{cyto_gatingTemplate_active()} by default.
#' @param axes_trans object of class
#'   \code{\link[flowWorkspace:transformerList]{transformerList}} generated by a
#'   \code{cyto_transformer} which contains the transformer definitions used to
#'   transform the data. Transformer definitions are only required when a
#'   flowSet object is supplied.
#' @param axes_limits options include \code{"auto"}, \code{"data"} or
#'   \code{"machine"} to use optimised, data or machine limits respectively. Set
#'   to \code{"machine"} by default to use entire axes ranges. Fine control over
#'   axes limits can be obtained by altering the \code{xlim} and \code{ylim}
#'   arguments.
#' @param spillover superseded by the \code{save_as} argument above, only
#'   included for backwards compatibility with older versions of CytoExploreR.
#' @param heatmap logical indicating whether the computed spillover matrix
#'   should be displayed in a heatmap, set to TRUE by default.
#' @param events number of events to extract from each control prior to fitting
#'   RLM models, set to 500 events by default.
#' @param model indicates the type of model to use when running autospill,
#'   options include \code{"rlm"} for robust linear models or \code{"vwqr"} for
#'   variance weighted quantile regression used in \code{CytoDecode}, set to
#'   \code{"rlm"} by default for speed and backwards compatibility.
#' @param max_iter indicates the maximum number of allowable iterations for
#'   refining the spillover coefficients, set to 20 by default.
#' @param trim proportion of events to exclude from the top and bottom of each
#'   scale when fitting models in \code{AutoSpill} and \code{CytoDecode}
#'   methods, set to 0.001 by default.
#' @param tol tolerance level for convergence of vwqr model in \code{CytoDecode}
#'   method, set to \code{1e-6} by default.
#' @param grid_size size of the grid to use for wvqr model in \code{CytoDecode}
#'   method, set to 100 by default. Smaller grid sizes will provide a speed
#'   boost at the cost of accuracy.
#' @param resid indicates whether to use \code{"lower"}, \code{"upper"} or
#'   \code{"both"} residuals when fitting variance models in vwqr used in
#'   \code{CytoDecode}, set to \code{"both"} by default.
#' @param details name of a CSV file to which the details of the single colour
#'   controls should be saved, set to NULL by default to use
#'   \code{date-Control-Details.csv}. Setting this argument to \code{NA} will
#'   prevent details from being written to a CSV file.
#' @param rerun logicla indicating whether to bypass gating and simply rerun the
#'   algorithm using existing gates, set to FALSE by default.
#' @param ... additional arguments passed to \code{\link{cyto_plot}}.
#'
#' @return spillover matrix and write spillover matrix to csv file named in
#'   accordance with \code{save_as}.
#'
#' @importFrom flowWorkspace cytoset
#' @importFrom openCyto gs_add_gating_method
#' @importFrom flowWorkspace gs_pop_remove
#' @importFrom HeatmapR heat_map
#' @importFrom data.table rbindlist `:=` as.data.table
#'
#' @examples
#' \dontrun{
#' library(CytoExploreRData)
#'
#' # Load in compensation controls
#' fs <- Compensation
#' gs <- GatingSet(Compensation)
#'
#' # Gate using cyto_gate_draw
#' gt <- Compensation_gatingTemplate
#' cyto_gatingTemplate_apply(gs, gt)
#'
#' # Channel match fille
#' cmfile <- system.file("extdata",
#'   "Compensation-Channels.csv",
#'   package = "CytoExploreRData"
#' )
#'
#' # Compute fluorescent spillover matrix
#' spill <- cyto_spillover_compute(
#'   gs,
#'   save_as = "Example-spillover.csv"
#' )
#'
#' # Compensate samples
#' gs <- cyto_compensate(gs, spill)
#'
#' }
#'
#' @seealso \code{\link{cyto_channel_match}}
#' @seealso \code{\link{cyto_spillover_edit}}
#' @seealso \code{\link{cyto_plot_compensation}}
#' @seealso \code{\link{cyto_compensate}}
#'
#' @author Dillon Hammill, \email{Dillon.Hammill@anu.edu.au}
#'
#' @references C. B. Bagwell & E. G. Adams (1993). Fluorescence spectral overlap
#'   compensation for any number of flow cytometry parameters. in: Annals of the
#'   New York Academy of Sciences, 677:167-184.
#'
#' @references Roca et al. (2021). AutoSpill is a principled framework that
#'   simplifies the analysis of multichromatic flow cytometry data. Nature
#'   Communications 12(2890).
#'
#' @export
cyto_spillover_compute <- function(x,
                                   parent = "root",
                                   select = NULL,
                                   channels = NULL,
                                   gate = "draw",
                                   type = "CytoDecode",
                                   save_as = NULL,
                                   gatingTemplate = NULL,
                                   axes_trans = NA,
                                   axes_limits = "machine",
                                   spillover = NULL,
                                   heatmap = TRUE,
                                   events = 500,
                                   model = "rlm",
                                   max_iter = 20,
                                   trim = 0.001,
                                   tol = 1e-6,
                                   grid_size = 100,
                                   resid = "both",
                                   details = NULL,
                                   rerun = FALSE,
                                   ...) {
  
  # SPILLOVER ------------------------------------------------------------------
  
  # BACKWARDS COMPATIBILITY
  if(!is.null(spillover)) {
    warning(
      paste0(
        "'spillover' is now deprecated in favour of 'save_as' - ",
        "please use that argument instead."
      )
    )
    save_as <- spillover
  }
  
  # CYTO_PLOT() ARGUMENTS
  args <- list(...)
  
  # CHANNEL_MATCH DEPRECIATED
  if("channel_match" %in% names(args)) {
    stop(
      paste0(
        "'channel_match' is no longer supported. CytoExploreR will ",
        "automatically create and search for a file called ",
        "'Control-Details.csv'."
      )
    )
  }
  
  # INTERNAL UNMIX ARGUMENT - COMPUTE UNMIXING MATRIX?
  unmix <- FALSE
  if("unmix" %in% names(args)) {
    unmix <- args[["unmix"]]
    args <- args[-match("unmix", names(args))]
  }
  
  # PREPARE DATA ---------------------------------------------------------------
  
  # NOTE: GATES ONLY ATTACHED TO SELECTED SAMPLES
  
  # # SELECT CONTROLS
  # x <- cyto_select(
  #   x,
  #   select
  # )
  
  # CHANNELS
  if(is.null(channels)) {
    # DEFAULT TO -A FLUORESCENT CHANNELS
    channels <- cyto_fluor_channels(x)
    # DEFAULT - ALL AREA PARAMETERS
    rm_idx <- grep(
      "\\-[HW]$",
      channels,
      ignore.case = TRUE
    )
    if(length(rm_idx) > 0) {
      channels <- channels[
        -rm_idx
      ]
    }
  # USE PROVIDED CHANNELS
  } else {
    channels <- unique(
      cyto_channels_extract(
        x, 
        channels
      )
    )
  }
  names(channels) <- unname(channels)
  
  # MATCH CHANNELS
  pd <- cyto_channel_match(
    x,
    channels = channels,
    save_as = details,
    peaks = TRUE
  )
  pd <- pd[
    match(
      rownames(cyto_details(x)),
      rownames(pd)
    ),
    ,
    drop = FALSE
  ]
  
  # CHECK COMPENSATION DETAILS
  # CHANNEL CAN BE INVALID FOR UNMIXED DATA - USE LABEL INSTEAD
  lapply(
    seq_len(nrow(pd)),
    function(z) {
      # CHANNEL
      if(!pd$channel[z] %in% c("Unstained",
                               "unstained",
                               cyto_channels(x))) {
        stop(
          paste0(
            pd$channel[z], 
            " is not a valid channel for this ", 
            cyto_class(x), 
            "!"
          )
        )
        # PARENT
        if(cyto_class(x, "GatingSet")) {
          cyto_nodes_convert(x, pd$parent[z]) # ERRORS IF MISSING
        }
      }
    }
  )
  
  # MISSING VARIABLES
  vars <- c("name", "group", "parent", "channel", "marker", "label", "select")
  if(!all(vars %in% colnames(pd))) {
    stop(
      paste0(
        "cyto_details(x) is missing required variables: ",
        paste0(
          vars[!vars %in% colnames(pd)],
          collapse = " & "
        )
      )
    )
  }
  
  # DECOMPENSATE
  if(cyto_class(x, "GatingSet")) {
    spill <- cyto_spillover_extract(x)
    if(!is.null(spill)) {
      x <- cyto_compensate(
        x,
        spillover = spill,
        remove = TRUE,
        quiet = FALSE
      )
    }
  }
  
  # TRANSFORMATIONS
  if(.all_na(axes_trans)) {
    axes_trans <- cyto_transformers_extract(x)
  }
  
  # PREPARE TYPE - SUPPORT AUTOCOMP & AUTOSPILL
  if(grepl("^b|comp", type, ignore.case = TRUE)) {
    type <- "Bagwell"
  } else if(grepl("^r|spill", type, ignore.case = TRUE)) {
    type <- "Roca"
  } else if(grepl("^d|cy", type, ignore.case = TRUE)) {
    type <- "CytoDecode"
  } else {
    stop(
      "'type' must be either Autocomp, AutoSpill or CytoDecode!"
    )
  }
  
  # NOTE: MANUAL GATING IS DEFAULT - OPTION DRAW | AUTO | TRUE -> DRAW | FALSE
  # PREPARE GATING ARGUMENT
  if(gate %in% c(FALSE, NA)) {
    if(!type %in% "Bagwell") {
      gate <- NA
    } else {
      gate <- "draw-2d"
    }
  } else if(gate %in% TRUE) {
    gate <- "draw-2d"
  } else if(grepl("draw|1d|2d", gate, ignore.case = TRUE)) {
    if(!cyto_interactive()) {
      warning(
        "Manual gating is only supported in interactive CytoExploreR sessions! \n",
        "Using automated gating instead..."
      )
      gate <- "auto"
    } else {
      # DEFAULT IS 2D GATING NOW
      if(grepl("1d", gate, ignore.case = TRUE)) {
        gate <- "draw-1d"
      } else {
        gate <- "draw-2d"
      }
    }
  } else {
    gate <- "auto"
  }
  
  # NOTE: TRANSFORMATIONS ARE NOW APPLIED IN PLACE
  
  # TRANSFORMED DATA REQUIRED FOR GATING
  if(!.all_na(gate)) {
    if(any(!channels %in% names(axes_trans))) {
      # TODO: SWITCH TO ARCSINH HERE
      # DEFINE NEW TRANSFORMERS
      trans_new <- cyto_transformers_define(
        x, 
        channels = channels[!channels %in% names(axes_trans)],
        type = "asinh",
        plot = FALSE,
        progress = FALSE
      )
      # REVERSE OLD TRANSFORMERS
      if(!.all_na(axes_trans)) {
        x <- suppressWarnings(
          cyto_transform(
            x,
            trans = axes_trans,
            copy = FALSE,
            inverse = TRUE,
            plot = FALSE,
            quiet = TRUE
          )
        )
        axes_trans <- cyto_transformers_combine(axes_trans, trans_new)
      } else {
        axes_trans <- trans_new
      }
      # APPLY COMBINED TRANSFORMERS IN PLACE
      x <- suppressWarnings(
        cyto_transform(
          x,
          trans = axes_trans,
          copy = FALSE,
          inverse = FALSE,
          plot = FALSE,
          quiet = TRUE
        )
      )
    }
  }
  
  # RESTRICT TRANSFORMERS TO CHANNELS
  if(!.all_na(axes_trans)) {
    if(any(channels %in% names(axes_trans))) {
      axes_trans <- cyto_transformers_combine(
        axes_trans[names(axes_trans) %in% channels]
      )
    } else {
      axes_trans <- NA
    }
  }
  
  # SPILLOVER TEMPLATE
  spill_mat <- matrix(
    0,
    ncol = length(channels),
    nrow = length(channels),
    dimnames = list(unname(channels), unname(channels))
  )
  diag(spill_mat) <- 1
  
  # PREPARE GATINGTEMPLATE -----------------------------------------------------

  # STORE GATES FOR BAGWELL & HYBRID METHODS
  if(cyto_class(x, "GatingSet") & !.all_na(gate)) {
    # CHECK IF GATINGTEMPLATES ARE BEING USED
    if(!cyto_option("CytoExploreR_gatingTemplate") %in% FALSE) {
      # ACTIVE GATINGTEMPLATE
      if(is.null(gatingTemplate)) {
        gatingTemplate <- cyto_gatingTemplate_active(
          ask = TRUE
        )
      }
      # CREATE GATINGTEMPLATE
      if(!file_exists(gatingTemplate)) {
        cyto_gatingTemplate_create(
          gatingTemplate,
          active = TRUE
        )
      }
    } else {
      gatingTemplate <- NULL
    }
  }

  # GATED POPULATIONS ----------------------------------------------------------

  # EXTRACT NODES FROM GATINGSET
  # NOTE: ALL SAMPLES HAVE THE SAME GATES
  if(cyto_class(x, "GatingSet")) {
    nodes <- cyto_nodes(
      x,
      path = "full"
    )
  } else {
    nodes <- NULL
  }

  # SPILLOVER COMPUTATION ------------------------------------------------------

  # MESSAGE REFERENCE
  message(
    "Computing ",
    if(unmix){"unmixing "} else {"spillover "},
    "matrix using the ",
    type, 
    " method... \n"
  )
  
  # BAGWELL & HYBRID METHODS REQUIRE GATING
  if(!.all_na(gate)) {

    # SPLIT CYTOSET|GATINGSET SAMPLES INTO GROUPS
    cyto_list <- cyto_group_by(
      x,
      group_by = "group"
    )
    
    # GATE POPULATIONS & COMPUTE SPILLOVER COEFFICIENTS - DROP GROUPING
    gate_list <- list()
    gate_edit <- list()
    pops <- do.call(
      "c",
      lapply(
        seq_along(cyto_list),
        function(id) {
          # GROUP
          group <- names(cyto_list)[id]
          # GROUP CYTOSET/GATINGSET
          cyto <- cyto_list[[id]]
          # EXPERIMENT DETAILS
          pd <- cyto_details(cyto)
          # LOCATE GROUP STAINED CONTROLS
          idx <- seq_along(cyto)[
            !grepl("Unstained", pd$channel, ignore.case = TRUE)
          ]
          # LOCATE UNSTAINED CONTROLS
          unst_idx <- seq_along(cyto)[-idx]
          # LOCATE GROUP SELECTED STAINED CONTROLS
          idx <- idx[as.logical(pd$select[idx])]
          names(idx) <- cyto_names(cyto)[idx]
          # LOCATE GROUP SELECTED UNSTAINED CONTROLS
          if(length(unst_idx) > 0) {
            unst_idx <- unst_idx[as.logical(pd$select[unst_idx])]
            names(unst_idx) <- cyto_names(cyto)[unst_idx]
          }
          # NO STAINED CONTROLS FOR GROUP
          if(length(idx) == 0){
            return(NULL)
          }
          # LOOP THROUGH MARKER & DYE COMBINATIONS
          pops <- lapply(
            idx,
            function(z) {
              # <MARKER> LABEL
              nm <- paste0(
                "<",
                pd$marker[z],
                "> ",
                pd$label[z]
              )
              # PARENT
              parent <- pd$parent[z]
              # PEAK DETECTOR
              peak <- pd$channel[z]
              # CHANNELS TO COMPUTE SPILLOVER
              # DYE LABEL
              label <- pd$label[z]
              if(!is.null(label)) {
                if(label %in% c("NA", "", NA)) {
                  label <- NULL
                }
              }
              # GATED POPULATIONS - REPLACE ILLEGAL CHARACTERS FROM NAME
              pops <- paste0(
                gsub(
                  "[\\|\\&|\\:|\\,|\\/]",
                  "-",
                  nm
                ),
                c("-", "+")
              )
              # LOCATE BEST UNSTAINED CONTROL - LOWEST CV IN PEAK DETECTOR
              if(length(unst_idx) > 1) {
                # COMPUTE CV IN PEAK DETECTOR
                # NOTE: CANNOT UPDATE SELECTION IN PDATA AS CHANGES PER FILE
                # NOTE: PARENT MAY VARY BY CONTROL SO WE NEED TO DO THIS HERE
                # NOTE: ONLY PEAK DETECTOR  USED FOR SPEED
                unst_idx <- unst_idx[
                  which.min(
                    cyto_apply(
                      cyto[unst_idx],
                      "cyto_stat_rcv",
                      parent = parent,
                      channels = peak, # ALL CHANNELS IS SLOW & REPETITIVE
                      input = "matrix",
                      inverse = TRUE,
                      copy = TRUE
                    )
                  )
                ]
              }
              
              # NEGATIVE & POSITIVE POPULATIONS (MAY BE CYTOSETS ALREADY)
              # NOTE: EVENTS BARCODES NOT REQUIRED AS OVERLAY NOT USED
              # WE USE SMAPLE-ID TO OFFSET THEN DISPLAY MERGED DATA
              
              # PARENT POPULATIONS -------------------------------------------
              if(length(unst_idx) == 1) {
                neg_pop <- cyto_data_extract(
                  cyto[unst_idx],
                  parent = parent,
                  channels = channels,
                  format = "cytoframe",
                  # events = events,
                  inverse = FALSE,
                  copy = TRUE
                )[[1]][[1]]
                # APPEND SAMPLE-ID
                if(grepl("2d", gate)) {
                  neg_pop <- cyto_cbind(
                    neg_pop,
                    matrix(
                      1,
                      nrow = nrow(neg_pop),
                      ncol = 1,
                      dimnames = list(
                        NULL,
                        "Sample-ID"
                      )
                    )
                  )
                }
              } else {
                neg_pop <- NULL
              }
              pos_pop <- cyto_data_extract(
                cyto[z],
                parent = parent,
                channels = channels,
                format = "cytoframe",
                # events = events,
                inverse = FALSE,
                copy = TRUE
              )[[1]][[1]]
              if(grepl("2d", gate)) {
                pos_pop <- cyto_cbind(
                  pos_pop,
                  matrix(
                    if(length(unst_idx) == 1) {
                      2
                    } else {
                      1
                    },
                    nrow = nrow(pos_pop),
                    ncol = 1,
                    dimnames = list(
                      NULL,
                      "Sample-ID"
                    )
                  )
                )
              }
              
              # POSITIVE & NEGATIVE CYTOSET
              pop <- list(
                "+" = pos_pop,
                "-" = neg_pop
              )
              pop <- pop[!sapply(pop, "is.null")]
              pop <- cytoset(pop)
              
              # BARCODING REQUIRED FOR 1D OVERLAYS
              if(grepl("1d", gate) & length(pop) > 1) {
                pop <- cyto_barcode(pop, "events")
              }
              
              # FREE UP SOME MEMORY
              rm(neg_pop, pos_pop)
              
              # EXISTING GATES -----------------------------------------------
              
              # NO EXISTING GATES
              gates <- NA
              
              # CHECK GATINGSET FOR GATES
              if(cyto_class(cyto, "GatingSet")) {
                # LOCATE NEGATIVE GATE
                neg_ind <- grep(
                  gsub(
                    "\\-",
                    "\\\\-",
                    paste0(parent, "\\/", pops[1])
                  ),
                  nodes
                )
                # EXTRACT NEGATIVE GATE
                neg_gt <- NULL
                if(length(neg_ind) == 1) {
                  neg_gt <- cyto_gate_extract(
                    cyto[
                      if(length(unst_idx) == 0) {
                        z
                      } else {
                        unst_idx
                      } 
                    ],
                    parent = parent,
                    alias = nodes[neg_ind]
                  )[[1]][[1]]
                }
                # EXTRACT POSITIVE GATE
                pos_ind <- grep(
                  gsub(
                    "\\+",
                    "\\\\+",
                    paste0(parent, "\\/", pops[2])
                  ),
                  nodes
                )
                # EXTRACT POSITIVE GATE
                pos_gt <- NULL
                if(length(pos_ind) == 1) {
                  pos_gt <- cyto_gate_extract(
                    cyto[z],
                    parent = parent,
                    alias = nodes[pos_ind]
                  )[[1]][[1]]
                }
                # COMBINE GATES FOR PLOTTING
                gates <- structure(
                  list(
                    neg_gt,
                    pos_gt
                  ),
                  names = pops
                )
                # REMOVE MISSING GATES
                gates[LAPPLY(gates, "is.null")] <- NULL
                if(length(gates) == 0) {
                  gates <- NA
                }
              }
              
              # CYTO_PLOT() --------------------------------------------------
              
              # NOTE: WE MAY NEED TO SUPPORT HISTOGRAM GATING HERE
              
              # CYTO_PLOT
              if(grepl("draw", gate)) {
                do.call(
                  "cyto_plot",
                  c(
                    list(
                      "x" = if(grepl("1d", gate)) {
                        pop[1]
                      } else {
                        pop
                      },
                      # NOTE: IF GATES EXIST WE GATE IN THE SAME DIMENSION
                      "channels" = c(
                        peak,
                        if(grepl("2d", gate)) {
                          "Sample-ID"
                        } else {
                          NULL
                        }
                      ),
                      "merge_by" = if(grepl("2d", gate)) {
                        "all"
                      } else {
                        "name"
                      },
                      "overlay" = if(grepl("1d", gate) & length(pop) > 1) {
                        pop[2]
                      } else {
                        NA
                      },
                      "gate" = gates,
                      "gate_line_col" = "magenta",
                      "gate_line_alpha" = 0.5,
                      "title" = paste0(
                        cyto_names(cyto)[z],
                        "\n",
                        parent
                      ),
                      "axes_limits" = "data",
                      "axes_trans" = axes_trans,
                      "legend" = FALSE,
                      hist_stack = 0,
                      hist_layers = length(pop),
                      ylab = if(grepl("2d", gate)) {
                        "Single Colour Control"
                      } else {
                        "% of Mode"
                      },
                      axes_text = list(
                        list(
                          "label" = NULL,
                          "at" = NULL,
                          "add" = TRUE
                        ),
                        if(grepl("1d", gate)) {
                          list(
                            "label" = NULL,
                            "at" = NULL,
                            "add" = TRUE
                          )
                        } else {
                          list(
                            "label" = c(
                              if(length(pop) > 1) {"Unstained"}else{NULL},
                              paste0(
                                if(length(label) > 0) {
                                  label
                                } else {
                                  peak
                                },
                                "+"
                              )
                            ),
                            "at" = c(1, if(length(pop) > 1) {2} else{NULL}),
                            "add" = TRUE,
                            "las" = 0
                          )
                        }
                      ),
                      label = FALSE,
                      ylim = if(grepl("2d", gate)) {
                        c(0, length(pop) + 1)
                      } else {
                        NA
                      }
                    ),
                    args
                  )
                )
              }
              
              # GATING -------------------------------------------------------
              
              # TODO: WE NEED TO CARRY INFORMATIVE GROUP NAMES 
              
              # MANUAL GATING - BYPASS GATE EDITING
              if(grepl("draw", gate)) {
                # CHECK & EDIT GATES
                if(!rerun) {
                  # GATE NEGATIVE POPULATION
                  neg_gt <- cyto_func_call(
                    "cyto_gate_draw",
                    list(
                      pop[length(pop)],
                      "alias" = pops[1],
                      "channels" = peak,
                      "type" = "interval",
                      "gate" = if(!.all_na(gates)) {
                        gates[[1]]
                      } else{
                        NA
                      },
                      "plot" = FALSE
                    )
                  )[[1]][[1]]
                  neg_gt@filterId <- pops[1]
                  # GATE POSITIVE POPULATION
                  pos_gt <- cyto_func_call(
                    "cyto_gate_draw",
                    list(
                      pop[1],
                      "alias" = pops[2],
                      "channels" = peak,
                      "type" = "interval",
                      "gate" = if(!.all_na(gates)) {
                        gates[[2]]
                      } else{
                        NA
                      },
                      "plot" = FALSE
                    )
                  )[[1]][[1]]
                  pos_gt@filterId <- pops[2]
                }
                gates <- filters(
                  structure(
                    list(
                      neg_gt,
                      pos_gt
                    ),
                    names = pops
                  )
                )
                # AUTOMATED GATING REQUIRED
              } else {
                gate <- "auto"
              }
              
              # AUTOMATED GATING
              if(gate == "auto") {
                if(!rerun) {
                  gates <- watershed_1d(
                    pop[[1]],
                    x_control = if(length(pop) == 2) {
                      pop[[2]]
                    } else {
                      NULL
                    },
                    channel = peak,
                    peak = TRUE
                  )
                  gates <- gates[c(1, length(gates))]
                  names(gates) <- pops
                } else {
                  gates <- filters(
                    structure(
                      list(
                        neg_gt,
                        pos_gt
                      ),
                      names = pops
                    )
                  )
                }
                # NOTE: STATS ARE DISPLAYED FOR STAINED CONTROL DATA - ONLY
                # NOTE: ONLY NEW GATES ARE DISPLAYED
                do.call(
                  "cyto_plot",
                  c(
                    list(
                      "x" = pop,
                      "channels" = peak,
                      "merge_by" = "name",
                      "overlay" = NA,
                      "gate" = gates,
                      "title" = paste0(
                        cyto_names(cyto)[z],
                        "\n",
                        parent
                      ),
                      "axes_limits" = "data",
                      "axes_trans" = axes_trans,
                      "legend" = FALSE,
                      "hist_stack" = 0,
                      "hist_layers" = 2,
                      "label_text" = c(pops, NA, NA),
                      "label_stat" = c("percent", "percent", NA, NA)
                    ),
                    args
                  )
                )
              }
              
              # STORE GATES --------------------------------------------------
              
              # GATES PER CONTROL
              gate_list[[cyto_names(cyto)[z]]] <<- gates
              
              # GATE EDIT CHECK
              gate_edit[[cyto_names(cyto)[z]]] <<- structure(
                c(
                  identical(neg_gt, gates[[1]]),
                  identical(pos_gt, gates[[2]])
                ),
                names = pops
              )
              
              # APPLY GATES --------------------------------------------------
              
              # RETURN GATED POPULATIONS - CURRENT SCALE
              cs <- cytoset(
                list(
                  "+" = cyto_gate_apply(
                    pop[1],
                    gate = gates[[2]]
                  )[[1]][[1]][[1]],
                  "-" = cyto_gate_apply(
                    pop[length(pop)],
                    gate = gates[[1]]
                  )[[1]][[1]][[1]]
                )
              )
              # UPDATE METADATA
              pData(cs) <- cbind(
                pData(cs),
                pd[
                  c(z, z),
                  c("group", "parent","channel","marker","label", "select"),
                  drop = FALSE
                ]
              )
              return(cs)
            }
          )
          gate_list <<- gate_list
          return(pops)
        }
      )
    )
    # DROP EMPTY GROUPS
    pops <- pops[!sapply(pops, "is.null")]
  # NO GATING REQUIRED
  } else {
    unst_idx <- grep(
      "Unstained",
      pData(x)$channel,
      ignore.case = TRUE
    )
    idx <- seq_along(x)
    if(length(unst_idx) > 0) {
      idx <- idx[-unst_idx]
    }
    idx <- idx[
      sapply(
        idx, 
        function(id){
          pData(x)$select[id] %in% "TRUE"
        }
      )
    ]
    names(idx) <- cyto_names(x)[idx]
    pops <- lapply(
      idx,
      function(id) {
        cs <- cyto_data_extract(
          x[id],
          parent = pData(x)$parent[id],
          channels = channels,
          format = "cytoset",
          inverse = FALSE,
          copy = TRUE
        )[[1]]
        return(cs)
      }
    )
  }
  
  # IDENTIFY BEST STAINED CONTROL PER DETECTOR - HIGHEST POSITIVE MEDFI
  if(!unmix) {
    cnt <- table(
      pd$channel[
        !pd$channel %in% c(NA, "", "NA", "Unstained") &
        pd$select
      ]
    )
    if(any(cnt > 1)) {
      message(
        "Identifying the best control for each dye..."
      )
      # NOTE: FOR UNGATED DATA - MEDIAN OF WHOLE FILE IS USED
      # DETECTORS WITH DUPLICATE CONTROLS
      detectors <- names(cnt)[cnt > 0]
      # CONTROLS TO REMOVE
      pops_rm <- LAPPLY(
        detectors,
        function(detector) {
          # LOCATE CONTROLS FOR THE SAME DETECTOR
          idx <- cyto_names(x)[
            which(
              pd$channel %in% detector
            )
          ]
          # PEAK DETECTOR
          peak <- pd$channel[
            match(idx[1], cyto_names(x))
          ]
          # COMPUTE MEDIAN OF POSITIVE POPULATION
          idx[
            !which.max(
              sapply(
                idx,
                function(id) {
                  median(
                    cyto_exprs(
                      pops[[id]][[1]],
                      channels = peak
                    )
                  )
                }
              )
            )
          ]
        }
      )
      # DROP POOR QUALITY CONTROLS
      pops <- pops[-pops_rm]
    }
  }

  # UPDATE SAMPLE SELECTION
  pData(x)$select[match(names(pops), cyto_names(x))] <- "TRUE"
  
  # TODO: GH_POP_SET_GATE() + RECOMPUTE()
  # TODO: MANUAL GATINGTEMPLATE ENTRY
  
  # TODO: FOR SPEED WE COULD MODIFY GATES IN PLACE THEN REGENERATE GATINGTEMPLATE
  # STORE GATES IN GATINGSET & GATINGTEMPLATE
  if(cyto_class(x, "GatingSet") & !.all_na(gate)) {
    message(
      "Adding gates to GatingSet and gatingTemplate..."
    )
    # FOR EACH MARKER DYE COMBO PREPARE GATES FOR ALL SAMPLES ON EACH PARENT
    rm_idx <- which(
      pd$channel %in% c("Unstained", "unstained", "NA", NA, "") |
        !pd$select
    )
    # PREPARE GATE PREFIX
    nms <- paste0(
      "<",
      pd$marker,
      "> ",
      pd$label
    )
    # REPLACE ILLEGAL CHARACTERS
    nms <- gsub(
      "[\\|\\&|\\:|\\,|\\/]",
      "-",
      nms
    )
    # IMPORT GATINGTEMPLATE
    if(!is.null(gatingTemplate)) {
      gt <- cyto_gatingTemplate_read(
        gatingTemplate,
        data.table = TRUE
      )
      # GET GATINGTEMPLATE
      gT <- suppressPrint(
        gatingTemplate(gatingTemplate)
      )
    } else {
      gt <- NULL
      gT <- NULL
    }
    # UPDATE GATES IN GATINGSET & GATINGTEMPLATE
    lapply(
      unique(nms[-rm_idx]),
      function(nm) {
        # GET SAMPLE NAMES WITH MATCHING MARKER & LABEL
        ids <- cyto_names(x)[match(nm, nms)]
        # CREATE A GATE TEMPLATE
        gate <- structure(
          rep(list(NULL), length(x)),
          names = cyto_names(x)
        )
        # INHERIT GATES FOR GATED SAMPLES
        gate[ids] <- gate_list[ids]
        # USE SELECTED CONTROL GATES FOR OTHER CONTROLS
        if(length(ids) < length(x)) {
          # ONLY UPDATE SAMPLES WITHOUT GATES
          drop_idx <- match(ids, names(gate))
          # SELECT FIRST CONTROL COPY GATES TO OTHER SAMPLES
          id <- names(gate_list)[match(ids, names(gate_list))][1]
          # COPY GATES TO OTHER CONTROLS
          gate[-drop_idx] <- structure(
            rep(
              list(gate_list[[id]]),
              length(x) - length(ids)
            ),
            names = names(gate)[-drop_idx]
          )
        }
        # NAMES OF GATED POPULATIONS
        pops <- paste0(nm, c("-", "+"))
        names(pops) <- pops  # IMPORTANT FOR GATES
        parent <- pd$parent[match(ids, cyto_names(x))][1]
        # UPDATE POPULATIONS IN GATINGSET & GATINGTEMPLATE
        for(pop in pops) {
          pop_sub <- gsub(
            "([\\+\\-])",
            "\\\\\\1",
            paste0(
              parent, 
              "/", 
              pop
            )
          )
          # POP GATES
          gate_new <- lapply(
            gate,
            `[[`,
            pop
          )
          # UPDATE GATES IN GATINGSET
          if(any(grepl(pop_sub, nodes))) {
            gs_pop_set_gate(
              x,
              pop,
              gate_new,
              parent = parent
            )
          # ADD NEW POPULATION
          } else {
            gs_pop_add(
              x,
              gate_new,
              parent = parent
            )
          }
          # UPDATE GATES IN GATINGTEMPLATE
          if(!is.null(gt)) {
            # PREPARE GATES FOR GATINGTEMPLATE
            gate_new <- lapply(
              gate_new,
              function(g) {
                filters(
                  list(
                    g
                  )
                )
              }
            )
            # POPULATION EXISTS IN GATINGTEMPLATE
            if(any(grepl(pop_sub, cyto_nodes(gt)))) {
              # EXTRACT GATINGTEMPLATE GATES
              gt_gate <- eval(
                gt_get_gate(
                  gT,
                  cyto_nodes_convert(
                    gT,
                    nodes = parent,
                    path = "full"
                  ),
                  cyto_nodes_convert(
                    gT,
                    nodes = pop,
                    path = "full"
                  )
                )@args$gate
              )
              # UPDATE GATES
              gt_gate[names(gate_new)] <- gate_new
              # UPDATE GATINGTEMPLATE
              gating_args <- NULL
              alias <- NULL
              prnt <- parent
              # TODO: IMPROVE MATCHING HERE
              gt[
                alias == pop & parent == prnt,
                gating_args := CytoExploreR_.argDeparser(
                  list(
                    "gate" = gt_gate,
                    "openCyto.minEvents" = -1
                  )
                )
              ]
            # POPULATION MISSING FROM GATINGTEMPLATE
            } else {
              gt <- rbindlist(
                list(
                  gt, 
                  as.data.table(
                    list(
                      "alias" = basename(pop),
                      "pop" = "+",
                      "parent" = parent,
                      "dims" = parameters(gate_new[[1]][[1]]),
                      "gating_method" = "cyto_gate_draw",
                      "gating_args" = CytoExploreR_.argDeparser(
                        list(
                          "gate" = gate_new,
                          "openCyto.minEvents" = -1
                        )
                      ),
                      "collapseDataForGating" = TRUE,
                      "groupBy" = NA,
                      "preprocessing_method" = "pp_cyto_gate_draw",
                      "preprocessing_args" = NA
                    )
                  )
                )
              )
            }
            # RE-WRITE GATINGTEMPLATE
            cyto_gatingTemplate_write(
              gt,
              gatingTemplate
            )
          }
        }
        # # GATE ALREADY EXISTS
        # if(any(
        #   sapply(paste0(parent, "/", pops), function(w){
        #     w <- gsub("\\-", "\\\\-", w)
        #     w <- gsub("\\+", "\\\\+", w)
        #   any(grepl(w, nodes))
        # }))) {
        #   cyto_gate_remove(
        #     x,
        #     parent = parent,
        #     alias = pops,
        #     gatingTemplate = gatingTemplate
        #   )
        # }

        # # ADD GATES TO GATINGSET & GATINGTEMPLATE
        # lapply(
        #   pops,
        #   function(pop) {
        #     gt <<- rbind(
        #       gt,
        #       .suppress_all_messages(
        #         gs_add_gating_method(
        #           gs = x,
        #           alias = pop,
        #           parent = parent,
        #           pop = "+",
        #           dims = parameters(gate[[1]][[1]]),
        #           gating_method = "cyto_gate_draw",
        #           gating_args = list(
        #             "gate" = filters(
        #               lapply(
        #                 gate,
        #                 `[[`,
        #                 gsub("\\\\", "", pop)
        #               )
        #             ),
        #             "openCyto.minEvents" = -1
        #           ),
        #           groupBy = NA,
        #           collapseDataForGating = TRUE,
        #           preprocessing_method = "pp_cyto_gate_draw"
        #         )
        #       )
        #     )
        #   }
        # )
        # WRITE UPDATED GATINGTEMPLATE - WRITING ERROR - SYNC GS
        if(!is.null(gatingTemplate)) {
          cyto_gatingTemplate_write(
            gt,
            gatingTemplate
          )
        }
      }
    )
    # UPDATE GATING
    recompute(x)
  }
  
  # BAGWELL SPILLOVER
  if(type == "Bagwell") {
    message(
      paste0(
        "C. B. Bagwell & E. G. Adams (1993). Fluorescence spectral ",
        "overlap compensation for any number of flow cytometry parameters.",
        " in: Annals of the New York Academy of Sciences, 677:167-184.", 
        "\n"
      )
    )
    # COMPUTE MEDFI OF NEGATIVE & POSITIVE POPULATIONS
    spill <- do.call(
      "rbind",
      lapply(
        seq_along(pops),
        function(id) {
          # PEAK DETECTOR
          peak <- pData(pops[[id]])$channel[1]
          # COMPUTE MEDFI
          medfi <- cyto_apply(
            pops[[id]],
            channels = channels,
            FUN = "cyto_stat_median",
            round = 4,
            input = "matrix",
            trans = axes_trans,
            inverse = TRUE,
            copy = TRUE
          )
          # SUBTRACT BACKGROUND
          medfi <- (medfi[1, , drop = FALSE] - medfi[2, , drop = FALSE])
          rownames(medfi) <- if(unmix) {
            if(pData(pops[[id]])$marker[1] %in% c("", "NA", NA)) {
              paste0(
                "<NA> ",
                pData(pops[[id]])$label[1]
              )
            } else {
              paste0(
                "<",
                pData(pops[[id]])$marker[1],
                "> ",
                pData(pops[[id]])$label[1]
              )
            }
          } else {
            peak
          }
          # NORMALISE
          return(
            medfi/medfi[1, peak]
          )
        }
      )
    )
  # AUTOSPILL OR CytoDecode SPILLOVER
  } else {
    # GATED DATA - SAMPLE & MERGE UNSTAINED AND STAINED DATA
    pops <- cytoset(
      do.call(
        "c",
        lapply(
          pops,
          function(pop) {
            # EQUAL SAMPLE SIZE FOR BOTH POPULATIONS
            if(length(pop) >  1) {
              cf <- cyto_merge_by(
                pop,
                merge_by = "all",
                format = "cytoframe",
                events = min(c(events, nrow(pop)[[1]])),
                overwrite = FALSE
              )[[1]]
            # DOUBLE SAMPLE SIZE 
            } else {
              cf <- cyto_sample(
                pop[[1]],
                events = min(c(2*events, nrow(pop)[[1]]))
              )
            }
            return(cf)
          }
        )
      )
    )
    # UPDATE DETAILS
    pData(pops)[, c(
      "group",
      "parent",
      "channel", 
      "marker",
      "label",
      "select"
    )] <- 
      pd[
        match(cyto_names(pops), cyto_names(x)),
        c(
          "group",
          "parent",
          "channel", 
          "marker",
          "label",
          "select"
        )
      ]
    # AUTOSPILL & CytoDecode REQUIRE LINEAR DATA
    pops <- .suppress_all_messages(
      cyto_transform(
        pops,
        trans = axes_trans,
        inverse = TRUE,
        plot = FALSE
      )
    )
    # AUTOSPILL
    if(type %in% "Roca") {
      # MESSAGE REFERENCE
      message(
        paste0(
          "Roca et al. (2021). AutoSpill is a principled framework that ",
          "simplifies the analysis of multichromatic flow cytometry data. Nature",
          " Communications 12(2890)."
        )
      )
      # NOTE: PD$CHANNEL REQUIRED
      # REFINE SPILLOVER MATRIX
      if(unmix) {
        spill <- do.call(
          "rbind",
          lapply(
            seq_along(pops),
            function(id) {
              .cyto_asp_spill(
                pops[id],
                trans = axes_trans,
                channels = channels,
                model = model,
                max_iter = max_iter,
                trim = trim,
                unmix = unmix
              )
            }
          )
        )
      } else {
        spill <- .cyto_asp_spill(
          pops,
          trans = axes_trans,
          channels = channels,
          model = model,
          max_iter = max_iter,
          trim = trim,
          unmix = unmix
        )
      }
    # CYTODECODE
    } else {
      # PROGRESS BAR
      pb <- cyto_progress(
        label = "CytoDecode",
        total = length(pops),
        clear = FALSE
      )
      spill <- do.call(
        "rbind",
        lapply(
          seq_along(pops),
          function(id) {
            x_chan <- pData(pops)$channel[id]
            coef <- c()
            iter <- 0
            # NOTE: ASSIGNED PEAK DETECTOR NEEDS TO BE GOOD ENOUGH FOR GATING
            # ONLY 5 ATTEMPTS TO LOCATE PEAK DETECTOR
            while(iter <= 5) {
              iter <- iter + 1
              for(y_chan in channels) {
                # Y = X
                if(x_chan %in% y_chan) {
                  coef <- c(
                    coef,
                    structure(
                      1,
                      names = y_chan
                    )
                  )
                  # VWQR
                } else {
                  exprs <- cyto_data_extract(
                    pops[id], 
                    channels = c(
                      x_chan,
                      y_chan
                    ),
                    format = "matrix",
                    markers = TRUE,
                    inverse = TRUE,
                    copy = TRUE
                  )[[1]][[1]]
                  # OUTLIER REMOVAL
                  q <- quantile(exprs[, 1], c(trim, 1 - trim))
                  exprs <- exprs[
                    exprs[, 1] >= min(q) & exprs[, 1] <= max(q),
                    ,
                    drop = FALSE
                  ]
                  coef <- c(
                    coef,
                    structure(
                      coefficients(
                        vwqr_cpp(
                          data.frame(
                            "x" = exprs[, 1],
                            "y" = exprs[, 2]
                          ),
                          max_iter = max_iter,
                          residual_type = resid,
                          grid_size = grid_size,
                          tol = tol
                        )
                      )[2],
                      names = y_chan
                    )
                  )
                }
              }
              # PEAK DETECTOR CORRECT
              if(!unmix | all(coef <= 1)) {
                break
                # UPDATE PEAK DETECTOR
              } else {
                x_chan <- names(coef)[which.max(coef)][1]
                coef <- c()
              }
            }
            # PROGRESS BAR
            cyto_progress(pb)
            # RETURN COEFFICIENTS
            return(coef)
          }
        )
      )
      # FORMAT SPILLOVER MATRIX
      if(!unmix) {
        colnames(spill) <- channels
        rownames(spill) <- pData(pops)$channel
      } 
    }
    # FORMAT SPECTRA
    if(unmix) {
      colnames(spill) <- channels
      rownames(spill) <- sapply(
        seq_along(pops),
        function(id) {
          if(is.na(pData(pops)$marker[id])|.empty(pData(pops)$marker[id])) {
            paste0(
              "<NA> ",
              pData(pops)$label[id]
            )
          } else {
            paste0(
              "<",
              pData(pops)$marker[id],
              "> ",
              pData(pops)$label[id]
            )
          }
        }
      )
      spill[spill < 0] <- 0
    }
  }
  
  # CREATE SPILLOVER MATRIX
  if(!unmix) {
    res <- diag(
      1,
      nrow = length(channels),
      ncol = length(channels)
    )
    colnames(res) <- channels
    rownames(res) <- channels
    res[match(rownames(spill), rownames(res)), colnames(res)] <-
      spill[, colnames(res)]
    diag(res) <- 1
  # FORMAT UNMIXING MATRIX
  } else {
    res <- spill
  }

  # DEFAULT CSV FILENAME
  if (is.null(save_as)) {
    save_as <- cyto_file_name(
      paste0(
        format(
          Sys.Date(),
          "%d%m%y"
        ),
        if(!unmix) {
          "-Spillover-Matrix.csv"
        } else {
          "-Unmixing-Matrix.csv"
        }
      )
    )
  }

  # EXPORT SPILLOVER MATRIX TO CSV FILE
  if(!is.na(save_as)) {
    if (!cyto_class(save_as, "character")) {
      stop(
        "'save_as' should be the name of a csv file."
      )
    }
    write_to_csv(
      res,
      save_as,
      row.names = TRUE
    )
  }

  # HEATMAP
  if(heatmap) {
    if(!unmix) {
      diag(res) <- NA
    }
    # CONSTRUCT HEATMAP - USE CYTO_PLOT_HEATMAP?
    heat_map(
      res,
      cell_col_empty = "black",
      cell_col_scale = .cyto_plot_point_col_scale(),
      title = if(!unmix) {
        "Spillover Matrix"
      } else {
        "Spectral Unmixing Matrix"
      },
      cell_text = TRUE,
      tree_y = if(unmix & nrow(res) > 1) {
        TRUE
      } else {
        NULL
      }
    )
    if(!unmix) {
      diag(res) <- 1
    }
  }
  
  # RETURN SPILLOVER OR UNMIX
  return(res)
  
}

